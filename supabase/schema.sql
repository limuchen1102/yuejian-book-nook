create table if not exists public.books (
  id bigint generated by default as identity primary key,
  title text not null,
  author text not null,
  category text not null check (category in ('文学', '思想', '生活')),
  description text not null,
  cover text not null default 'orange',
  symbol text not null default '✦',
  created_at timestamptz not null default now()
);

alter table public.books enable row level security;

drop policy if exists "Books are publicly readable" on public.books;
create policy "Books are publicly readable" on public.books for select to anon, authenticated using (true);

